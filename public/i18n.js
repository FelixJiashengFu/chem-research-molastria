/* MolAstria i18n. Chinese is the source language in the HTML and scripts; English is applied in the
   browser from i18n/en.js (generated by tools/i18n-build.ts). Text nodes and a few attributes are
   matched whole, or against patterns with {0} {1} slots for the parts scripts fill in. Content that is
   data (crawled titles, excerpts, guide chapters, AI replies, SMILES) is left as written. */
(() => {
  'use strict';
  const root = document.documentElement;
  const params = (() => { try { return new URLSearchParams((window.__CHEM_LOCATION__ || location).search); } catch { return new URLSearchParams(); } })();
  if (params.get('lang') === 'en' || params.get('lang') === 'zh') {
    try { localStorage.setItem('chemhub-lang', params.get('lang')); } catch {}
    if (params.get('lang') === 'en') root.lang = 'en';
  }
  const lang = root.lang === 'en' ? 'en' : 'zh';
  const api = { lang, t: (s) => s, ready: Promise.resolve() };
  window.ChemI18n = api;
  if (lang !== 'en') { delete root.dataset.i18n; return; }

  const CJK = /[㐀-鿿！-～、-〿]/;
  const HAN = /[㐀-鿿]/;
  const SKIP = 'script,style,code,pre,textarea,[translate=no],.paper .title,.paper .authors,.paper .abstract,.paper .tag,.acct-digest,#digest-overview,.digest-preview li,.cai-msg.user,.cai-body,.cai-refs span,.guide-article,.smi,.why,.row-main h3,.excerpt,.card h3,.net-item h4,.net-item p,.rs-list,.cr-bgpick-name,.mcard h4';
  const ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
  const norm = (s) => s.replace(/\s+/g, ' ').trim();

  let exact = new Map(), patterns = [], pieces = [];
  function compile(dict) {
    exact = new Map();
    patterns = [];
    for (const [k, v] of Object.entries(dict)) {
      if (!v) continue;
      if (!/\{\d\}/.test(k)) { exact.set(k, v); continue; }
      const parts = k.split(/\{(\d)\}/);
      let re = '^', order = [], literal = '';
      parts.forEach((p, i) => {
        if (i % 2) { re += '([\\s\\S]*?)'; order.push(Number(p)); } else { re += p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); literal += p; }
      });
      if ((literal.match(new RegExp(HAN.source, 'g')) || []).length < 2) continue;
      // Anchor: the longest unbroken run of Chinese inside one literal piece (never spliced across a slot).
      const runs = parts.filter((_, i) => i % 2 === 0).flatMap((p) => p.match(/[㐀-鿿]+/g) || []);
      const anchor = runs.sort((a, b) => b.length - a.length)[0] || '';
      patterns.push({ re: new RegExp(re + '$'), order, en: v, weight: literal.length, anchor: anchor.slice(0, 2) });
    }
    patterns.sort((a, b) => b.weight - a.weight);
    // Pieces for text that scripts glue together with `+`: longest first, Chinese keys only.
    pieces = [...exact].filter(([k]) => HAN.test(k) && k.length <= 40).sort((a, b) => b[0].length - a[0].length);
  }
  const hasHan = (s) => HAN.test(s);
  function tr(raw, depth = 0) {
    if (!raw || !HAN.test(raw)) return raw;
    const lead = raw.match(/^\s*/)[0], trail = raw.match(/\s*$/)[0], core = norm(raw);
    let out = exact.get(core);
    if (out === undefined && depth < 3) {
      for (const p of patterns) {
        if (p.anchor && !core.includes(p.anchor)) continue;
        const m = core.match(p.re);
        if (!m) continue;
        // A slot that still holds untranslatable Chinese means the pattern matched the wrong text.
        const caps = m.slice(1).map((c) => tr(c, depth + 1));
        if (caps.some(hasHan)) continue;
        out = p.en.replace(/\{(\d)\}/g, (_, n) => { const i = p.order.indexOf(Number(n)); return i < 0 ? '' : caps[i]; });
        break;
      }
    }
    if (out === undefined) out = glue(core); // also for slot captures, e.g. a list followed by "等"
    return out === undefined ? raw : lead + out + trail;
  }
  /** Replace known pieces inside a string; accepted only when no Chinese is left over. */
  function glue(core) {
    let s = core;
    for (const [k, v] of pieces) {
      if (!s.includes(k)) continue;
      s = s.split(k).join(`\u0001${v}\u0001`);
      if (!hasHan(s.replace(/\u0001[^\u0001]*\u0001/g, ''))) break;
    }
    if (hasHan(s.replace(/\u0001[^\u0001]*\u0001/g, ''))) return undefined;
    return s.replace(/([\w)\]%])\u0001/g, '$1 ').replace(/\u0001(?=[\w(\[])/g, ' ').replace(/\u0001/g, '')
      .replace(/（/g, ' (').replace(/）/g, ')').replace(/：/g, ': ').replace(/，/g, ', ').replace(/；/g, '; ').replace(/。/g, '. ')
      .replace(/\s+([,.;:)])/g, '$1').replace(/\s{2,}/g, ' ').trim();
  }
  api.t = (s) => tr(String(s ?? ''));

  const done = new WeakMap();
  function translateText(node) {
    const v = node.nodeValue;
    if (!v || !HAN.test(v) || done.get(node) === v) return;
    const p = node.parentElement;
    if (!p || p.closest(SKIP)) return;
    const out = tr(v);
    done.set(node, out);
    if (out !== v) node.nodeValue = out;
  }
  function translateAttrs(el) {
    if (el.closest(SKIP)) return;
    for (const a of ATTRS) {
      const v = el.getAttribute(a);
      if (v && HAN.test(v)) { const out = tr(v); if (out !== v) el.setAttribute(a, out); }
    }
    if (el.tagName === 'OPTION' && el.label && HAN.test(el.label) && el.label !== el.text) el.label = tr(el.label);
  }
  function walk(rootNode) {
    if (rootNode.nodeType === 3) { translateText(rootNode); return; }
    if (rootNode.nodeType !== 1) return;
    translateAttrs(rootNode);
    const w = document.createTreeWalker(rootNode, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
      acceptNode: (n) => (n.nodeType === 1 && n.matches(SKIP) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT)
    });
    for (let n = w.nextNode(); n; n = w.nextNode()) n.nodeType === 3 ? translateText(n) : translateAttrs(n);
  }
  let pending = new Set(), scheduled = false;
  const flush = () => { scheduled = false; const list = [...pending]; pending = new Set(); for (const n of list) if (n.isConnected) walk(n); };
  const queue = (n) => { pending.add(n); if (!scheduled) { scheduled = true; queueMicrotask(flush); } };

  function start(dict) {
    compile(dict);
    walk(document.documentElement);
    document.title = tr(document.title);
    new MutationObserver((records) => {
      for (const r of records) {
        if (r.type === 'childList') r.addedNodes.forEach(queue);
        else if (r.type === 'characterData') queue(r.target);
        else if (r.type === 'attributes') queue(r.target);
      }
    }).observe(document.documentElement, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
    const titleEl = document.querySelector('title');
    if (titleEl) new MutationObserver(() => { const t = tr(document.title); if (t !== document.title) document.title = t; }).observe(titleEl, { childList: true });
    delete root.dataset.i18n;
    document.dispatchEvent(new Event('chemhub:i18n'));
  }
  const fromParent = () => { try { return window.parent !== window ? window.parent.CHEMHUB_I18N_EN : null; } catch { return null; } };
  const dict = window.CHEMHUB_I18N_EN || fromParent();
  if (dict) { start(dict); return; }
  const base = window.__CHEM_LINK__ ? new URL(window.__CHEM_LINK__('')) : new URL('.', document.currentScript.src);
  api.ready = new Promise((resolve) => {
    const s = document.createElement('script');
    s.src = String(new URL('i18n/en.js', base));
    s.onload = () => { start(window.CHEMHUB_I18N_EN || {}); resolve(); };
    s.onerror = () => { delete root.dataset.i18n; resolve(); };
    document.head.append(s);
  });
})();
