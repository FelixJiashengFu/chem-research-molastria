#!/usr/bin/env python3
"""Spectra Hall (public/spectra/): reference tables that other code needs as numbers.

  isotopes   relative atomic masses and natural isotopic abundances, from the molmass package (BSD-3-Clause, C. Gohlke),
             which tabulates the NIST "Atomic Weights and Isotopic Compositions" values
  xsf        four-Gaussian X-ray scattering-factor parameters, from pymatgen (MIT), file
             src/pymatgen/analysis/diffraction/atomic_scattering_params.json:
             f(s) = Z - 41.78214 s^2 sum_i a_i exp(-b_i s^2),  s = sin(theta)/lambda in 1/Angstrom

  pip install molmass
  curl -O https://raw.githubusercontent.com/materialsproject/pymatgen/master/src/pymatgen/analysis/diffraction/atomic_scattering_params.json
  python tools/spectra/tables.py atomic_scattering_params.json
"""
import json, os, sys
import molmass
from molmass import ELEMENTS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'public', 'spectra', 'sp-tables.js')

iso, xsf = {}, {}
asp = json.load(open(sys.argv[1]))
for el in ELEMENTS:
    rows = [[i.massnumber, round(i.mass, 7), round(i.abundance, 6)] for i in el.isotopes.values() if i.abundance > 0]
    if rows:
        iso[el.symbol] = {'z': el.number, 'm': round(el.mass, 5), 'i': sorted(rows)}
    if el.symbol in asp:
        xsf[el.symbol] = [v for pair in asp[el.symbol] for v in pair]
data = {'isotopes': iso, 'xsf': xsf, 'from': {'isotopes': f'molmass {molmass.__version__}', 'xsf': 'pymatgen atomic_scattering_params.json'}}
js = ('// Generated by tools/spectra/tables.py: do not edit by hand.\n'
      '// isotopes: element -> { z, m (standard atomic weight), i: [[mass number, relative atomic mass, natural abundance], ...] }, from molmass (BSD-3-Clause).\n'
      '// xsf: element -> [a1, b1, a2, b2, a3, b3, a4, b4] for f(s) = Z - 41.78214 s^2 sum a_i exp(-b_i s^2), from pymatgen (MIT).\n'
      '(function (root) { const T = ' + json.dumps(data, separators=(',', ':')) + ';\n'
      "  if (typeof module === 'object' && module.exports) module.exports = T; else root.MOLASTRIA_SPECTRA_TABLES = T;\n"
      "})(typeof self !== 'undefined' ? self : globalThis);\n")
open(OUT, 'w').write(js)
print(len(iso), 'elements with isotopes,', len(xsf), 'with scattering factors,', len(js) // 1024, 'KB')
