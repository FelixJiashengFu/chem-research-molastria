// 谱图馆：把 tools/spectra/calc/ 里 PySCF 算出的一个个 JSON 合成 public/spectra/sp-computed.js（页面读的那一份）。
//   node tools/spectra/build.mjs
// 只做整理，不改数值：振动模式留 [频率 cm⁻¹, 红外强度 km/mol, 拉曼活性 Å⁴/amu, 退偏比]，虚频单独记下（页面上说明、不画）；
// 电子激发留 [能量 eV, 振子强度]。
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const dir = new URL('./calc/', import.meta.url);
const out = { program: '', vib: {}, uv: {} };
for (const name of readdirSync(dir).filter((n) => n.endsWith('.json')).sort()) {
  const j = JSON.parse(readFileSync(new URL(name, dir), 'utf8'));
  out.program ||= j.program;
  if (name.startsWith('vib-')) {
    if (!j.units) throw new Error(`${name}: no "units" field, so it predates the intensity fix in calcs.py; recompute it`);
    const real = j.modes.filter((m) => m.freq > 0), imag = j.modes.filter((m) => m.freq <= 0).map((m) => m.freq);
    out.vib[j.id] = {
      smiles: j.smiles, method: j.method, basis: j.basis, deriv: j.deriv, atoms: j.geometry.length, dipole: j.dipole,
      ...(imag.length ? { imag } : {}),
      raman: real.some((m) => m.raman != null),
      modes: real.map((m) => [m.freq, +m.ir.toFixed(2), m.raman == null ? null : +m.raman.toFixed(2), m.depol == null ? null : +m.depol.toFixed(3)]),
    };
  } else if (name.startsWith('uv-')) {
    out.uv[j.id] = {
      smiles: j.smiles, basis: j.basis, geom: j.geometry_method, atoms: j.geometry.length,
      states: Object.fromEntries(Object.entries(j.states).map(([xc, list]) => [xc, list.map((s) => [+s.ev.toFixed(3), +s.f.toFixed(4)])])),
      ...(Object.values(j.states).some((l) => l.some((s) => !s.conv)) ? { unconverged: true } : {}),
    };
  }
}
const text = `// Generated by tools/spectra/build.mjs from tools/spectra/calc/*.json (PySCF, see tools/spectra/calcs.py): do not edit by hand.
// vib: modes are [frequency cm-1 (harmonic, unscaled), IR intensity km/mol, Raman activity A^4/amu or null, depolarisation ratio or null].
// uv: states are [vertical excitation energy eV, oscillator strength] for each functional.
window.MOLASTRIA_SPECTRA_COMPUTED = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../../public/spectra/sp-computed.js', import.meta.url), text);
console.log(`sp-computed.js: ${Object.keys(out.vib).length} vibrational, ${Object.keys(out.uv).length} electronic, ${(text.length / 1024).toFixed(1)} KB`);
