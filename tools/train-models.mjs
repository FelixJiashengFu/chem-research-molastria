// Weekly refresh of the model facts on the train page: checks every Hugging Face model link on public/train/index.html
// (still there, downloads, likes, last update, parameter count) and lists new small models from the labs the page follows.
// Writes public/train/models-live.js, which train.js reads. Runs every Thursday in .github/workflows/refresh-data.yml.
// Run: node tools/train-models.mjs        (on a machine with HTTPS scanning: NODE_USE_SYSTEM_CA=1)
import { readFileSync, writeFileSync } from 'node:fs';

const PAGE = new URL('../public/train/index.html', import.meta.url);
const OUT = new URL('../public/train/models-live.js', import.meta.url);
const API = 'https://huggingface.co/api/models';
const EXPAND = ['downloads', 'likes', 'lastModified', 'createdAt', 'gated', 'cardData', 'safetensors', 'pipeline_tag'].map((e) => `expand[]=${e}`).join('&');
// Labs whose new small models are worth a look for a chemistry agent.
const LABS = ['LiquidAI', 'Qwen', 'google', 'nvidia', 'ibm-granite', 'openbmb', 'mistralai', 'microsoft', 'HuggingFaceTB', 'allenai', 'meta-llama', 'deepseek-ai', 'internlm', 'OpenDFM', 'futurehouse', 'openai', 'meta-models', 'zai-org', 'moonshotai'];
const NEW_DAYS = 60, MAX_PARAMS = 40e9;
const TEXT_TASKS = new Set(['text-generation', 'image-text-to-text', 'any-to-any', 'audio-text-to-text']);
const VARIANT = /(gguf|awq|gptq|fp8|fp4|nvfp4|int4|int8|w4a16|w8a8|mlx|bnb|onnx|4bit|8bit|quantized|eagle|draft|mtp|-lora|dspark|corr|guard|reward|-base$)/i;
// A name that says 35B on a 0.4B checkpoint is a draft head or adapter, not the model.
const sizeInName = (id) => Math.max(0, ...[...id.matchAll(/(\d+(?:\.\d+)?)b(?![a-z])/gi)].map((m) => Number(m[1])));
const NOT_MODELS = new Set(['datasets', 'spaces', 'docs', 'blog', 'papers', 'collections', 'learn', 'models', 'organizations', 'settings', 'join', 'login', 'pricing']);

const html = readFileSync(PAGE, 'utf8');
const linked = [...new Set([...html.matchAll(/https:\/\/huggingface\.co\/([\w.-]+)\/([\w.-]+)/g)]
  .filter((m) => !NOT_MODELS.has(m[1])).map((m) => `${m[1]}/${m[2]}`))];

async function get(url) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': 'MolAstria catalogue (molastria.com)' } });
      if (res.status === 429 || res.status >= 500) { await new Promise((r) => setTimeout(r, 1500 * attempt)); continue; }
      return { status: res.status, body: res.ok ? await res.json() : null };
    } catch { await new Promise((r) => setTimeout(r, 1500 * attempt)); }
  }
  return { status: 0, body: null };
}
const facts = (m) => ({
  downloads: m.downloads ?? null, likes: m.likes ?? null, updated: (m.lastModified || '').slice(0, 10), created: (m.createdAt || '').slice(0, 10),
  gated: Boolean(m.gated), license: m.cardData?.license || '', params: m.safetensors?.total || null, task: m.pipeline_tag || '',
});
async function pool(items, n, fn) {
  const out = new Array(items.length); let next = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (next < items.length) { const i = next++; out[i] = await fn(items[i]); } }));
  return out;
}

// 1. Every model linked on the page.
const checked = await pool(linked, 6, async (id) => {
  const r = await get(`${API}/${id}?${EXPAND}`);
  return [id, r.body ? { ok: true, ...facts(r.body) } : { ok: false, status: r.status }];
});
const models = Object.fromEntries(checked);
const reachable = checked.filter(([, v]) => v.ok || v.status === 404 || v.status === 401).length;
if (reachable < linked.length * 0.8) {
  console.error(`Hugging Face answered for only ${reachable} of ${linked.length} links; keeping last week's file.`);
  process.exit(1);
}

// 2. New small text models from the labs above that the page does not list yet.
const since = Date.now() - NEW_DAYS * 864e5;
const known = new Set(linked.map((x) => x.toLowerCase()));
const fresh = [];
for (const lab of LABS) {
  const r = await get(`${API}?author=${lab}&sort=createdAt&direction=-1&limit=40&${EXPAND}`);
  for (const m of r.body || []) {
    const f = facts(m);
    if (!f.created || Date.parse(f.created) < since) continue;
    if (!TEXT_TASKS.has(f.task) || !f.params || f.params > MAX_PARAMS || VARIANT.test(m.id) || known.has(m.id.toLowerCase())) continue;
    if (sizeInName(m.id) && f.params < sizeInName(m.id) * 1e9 * 0.3) continue;
    fresh.push({ id: m.id, lab, ...f });
  }
}
fresh.sort((a, b) => (b.downloads || 0) - (a.downloads || 0));

const data = { checkedAt: new Date().toISOString().slice(0, 10), linked: linked.length, ok: checked.filter(([, v]) => v.ok).length, models, fresh: fresh.slice(0, 12), newDays: NEW_DAYS };
writeFileSync(OUT, `// Generated by tools/train-models.mjs every Thursday (refresh-data.yml). Do not edit by hand.\nwindow.MOLASTRIA_MODELS_LIVE = ${JSON.stringify(data, null, 1)};\n`);
const dead = checked.filter(([, v]) => !v.ok).map(([id, v]) => `${id} (${v.status})`);
console.log(`checked ${linked.length} links: ${data.ok} ok${dead.length ? `, not reachable: ${dead.join(', ')}` : ''}; ${fresh.length} new small models (showing ${data.fresh.length})`);
for (const m of data.fresh) console.log(`  new: ${m.id} ${(m.params / 1e9).toFixed(1)}B ${m.created} ${m.task} ${m.license} ↓${m.downloads}`);
