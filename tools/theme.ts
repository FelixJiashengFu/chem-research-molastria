// Dark mode for stylesheets written with literal colors.
// Every #hex in the listed CSS files becomes var(--t-<hex>); public/theme-auto.css then defines each
// variable twice: the original value for light, and an OKLCH lightness-flipped value for dark
// (hue kept, chroma tempered). Re-running is safe: already-converted files have no literals left,
// and the palette is rebuilt from the var names found in the files.
//   deno run --allow-read --allow-write tools/theme.ts
const root = new URL("../public/", import.meta.url);
const files = ["styles.css", "atlas/styles.css", "lab/lab.css"];

type Lab = { L: number; a: number; b: number };
const toLinear = (c: number) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const toGamma = (c: number) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);

function hexToRgba(hex: string): [number, number, number, number] {
  let h = hex.slice(1);
  if (h.length <= 4) h = [...h].map((c) => c + c).join("");
  const n = (i: number) => parseInt(h.slice(i, i + 2), 16) / 255;
  return [n(0), n(2), n(4), h.length === 8 ? n(6) : 1];
}
function rgbToOklab([r, g, b]: number[]): Lab {
  const [lr, lg, lb] = [r, g, b].map(toLinear);
  const l = Math.cbrt(0.4122214708 * lr + 0.5363325363 * lg + 0.0514459929 * lb);
  const m = Math.cbrt(0.2119034982 * lr + 0.6806995451 * lg + 0.1073969566 * lb);
  const s = Math.cbrt(0.0883024619 * lr + 0.2817188376 * lg + 0.6299787005 * lb);
  return {
    L: 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    a: 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    b: 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  };
}
function oklabToRgb({ L, a, b }: Lab): number[] {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}
const inGamut = (rgb: number[]) => rgb.every((c) => c >= -1e-4 && c <= 1 + 1e-4);

// Paper #f6f5ee -> ~#111814, ink #1d392e -> ~#e3e9df; mid-tones (accents) move up modestly.
function darkVariant(hex: string): string {
  const [r, g, b, alpha] = hexToRgba(hex);
  const lab = rgbToOklab([r, g, b]);
  // Translucent dark tints are shadows and backdrops: they stay dark.
  if (alpha < 1 && lab.L < 0.5) return "#000000" + Math.round(Math.min(1, alpha * 1.6) * 255).toString(16).padStart(2, "0");
  const C = Math.hypot(lab.a, lab.b), h = Math.atan2(lab.b, lab.a);
  let L = 1.289 - 1.1496 * lab.L;
  L = Math.min(0.955, Math.max(0.17, L));
  // Light washes become dark surfaces: keep a hint of their hue, no more.
  let C2 = lab.L > 0.8 ? Math.min(C, 0.03) * 0.9 : C * 0.92;
  let rgb = oklabToRgb({ L, a: C2 * Math.cos(h), b: C2 * Math.sin(h) });
  while (!inGamut(rgb) && C2 > 0.001) {
    C2 *= 0.92;
    rgb = oklabToRgb({ L, a: C2 * Math.cos(h), b: C2 * Math.sin(h) });
  }
  const out = rgb.map((c) => Math.round(Math.min(1, Math.max(0, toGamma(Math.min(1, Math.max(0, c))))) * 255));
  const parts = [...out, ...(alpha < 1 ? [Math.round(alpha * 255)] : [])];
  return "#" + parts.map((n) => n.toString(16).padStart(2, "0")).join("");
}

const normalize = (hex: string) => {
  let h = hex.slice(1).toLowerCase();
  if (h.length <= 4) h = [...h].map((c) => c + c).join("");
  return h;
};

const used = new Set<string>();
for (const file of files) {
  const url = new URL(file, root);
  let css: string;
  try { css = await Deno.readTextFile(url); } catch { continue; }
  const converted = css.replace(/#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b/g, (m) => `var(--t-${normalize(m)})`);
  for (const [, h] of converted.matchAll(/var\(--t-([0-9a-f]{6,8})\)/g)) used.add(h);
  if (converted !== css) await Deno.writeTextFile(url, converted);
}

const names = [...used].sort();
const light = names.map((h) => `--t-${h}:#${h}`).join(";");
const dark = names.map((h) => `--t-${h}:${darkVariant("#" + h)}`).join(";");
const out = `/* Generated by tools/theme.ts — do not edit by hand. ${names.length} colors. */
:root{${light}}
@media (prefers-color-scheme:dark){:root:not([data-theme=light]){${dark}}}
:root[data-theme=dark]{${dark}}
`;
await Deno.writeTextFile(new URL("theme-auto.css", root), out);
console.log(`theme-auto.css: ${names.length} colors from ${files.join(", ")}`);
